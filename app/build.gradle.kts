val apiBaseUrl: String = providers.fileContents(rootProject.layout.projectDirectory.file("local.properties"))
    .asText.orNull
    ?.lineSequence()
    ?.map { it.trim() }
    ?.firstOrNull { it.startsWith("API_BASE_URL=") }
    ?.substringAfter("=")
    ?.trim()
    ?.takeIf { it.isNotEmpty() }
    ?.let { if (it.endsWith("/")) it else "$it/" }
    ?: urlBasePorDefecto

